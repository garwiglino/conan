// iOS downloads only index.html. Keep every runtime image and its timing in it.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),dir=path.join(root,'sprites/personnages/pretre');
const read=f=>JSON.parse(fs.readFileSync(path.join(dir,f),'utf8'));
const png=f=>'data:image/png;base64,'+fs.readFileSync(path.join(dir,f)).toString('base64');
const meta=read('animations.json'),fx=read('sortileges.json'),joints=read('arm-joints.json');
const sockets=new Map(joints.map(j=>[j.clip+':'+j.frame,j.support[2]]));
const key=c=>[c.phase,c.direction,c.state].join(':');
const clips=Object.fromEntries(meta.clips.map(c=>[key(c),{
 row:c.sheetRow,durationsMs:c.durationsMs,totalMs:c.totalMs,loop:c.loop,
 impactMs:c.impactMs,activeMs:c.activeMs,
 palm:c.durationsMs.map((_,i)=>sockets.get(c.name+':'+(i+1)))
}]));
const data={version:'pretre-aseprite-v4',clips,
 sheets:meta.phaseSheets.map(s=>({size:s.size,png:png(s.file)})),
 effects:Object.fromEntries(fx.clips.map(c=>[key(c),{row:c.row}])),
 rear:png(fx.rear),front:png(fx.front),fxSize:fx.sheet,bolt:png('projectiles.png')};
const runtime=fs.readFileSync(path.join(root,'scripts/boss-runtime.js'),'utf8');
const block='// BEGIN BOSS ASSETS (generated by scripts/embed-boss.cjs)\nconst BOSS_ART='+JSON.stringify(data)+';\n'+runtime+'\n// END BOSS ASSETS';
const file=path.join(root,'index.html');let html=fs.readFileSync(file,'utf8');
if(html.includes('// BEGIN BOSS ASSETS'))html=html.replace(/\/\/ BEGIN BOSS ASSETS[^\n]*\n[\s\S]*?\/\/ END BOSS ASSETS/,()=>block);
else html=html.replace('// END GUARDIAN ASSETS','// END GUARDIAN ASSETS\n'+block);
fs.writeFileSync(file,html);
fs.writeFileSync(path.join(root,'ios/Conan/Game/index.html'),html.replace('<meta name="apple-mobile-web-app-title" content="Conan"><link rel="apple-touch-icon" href="icon-180.png"><link rel="manifest" href="manifest.webmanifest">',''));
const indexFile=path.join(root,'sprites/personnages/index.json'),index=JSON.parse(fs.readFileSync(indexFile,'utf8'));
for(const phase of [0,1]){
 const sheet=meta.phaseSheets[phase];
 index.personnages[phase?'pretre_du_serpent_rage':'pretre_du_serpent']={
  nom:'Le Prêtre du serpent'+(phase?' — enragé':''),fichier:'pretre/'+sheet.file,
  source:'pretre/pretre-animations.aseprite',manifest:'pretre/animations.json',lignes:sheet.size[1]/80,
  animations:meta.clips.filter(c=>c.phase===phase).map(c=>({ligne:c.sheetRow,animation:c.state,nom:c.label,direction:['haut','droite','bas','gauche'][c.direction],images:c.durationsMs.length,durees_ms:c.durationsMs,boucle:c.loop,impact_ms:c.impactMs,cadres:c.durationsMs.map((_,i)=>[i*80,c.sheetRow*80,80,80])}))
 };
}
fs.writeFileSync(indexFile,JSON.stringify(index,null,2)+'\n');
console.log('Embedded 124 boss clips, 24 layered spells and traveling jade projectiles; iOS synchronized.');
