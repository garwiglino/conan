// The installed iOS app updates index.html alone: keep its art self-contained.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const art = path.join(root, 'sprites/personnages');
const manifest = JSON.parse(fs.readFileSync(path.join(art, 'gardien-animations.json'), 'utf8'));
const clips = Object.fromEntries(manifest.clips.map(c => [c.direction + ':' + c.state, {
  row: c.row, durationsMs: c.durationsMs, handSocketPx: c.handSocketPx, loop: c.loop
}]));
const dataURL = file => 'data:image/png;base64,' + fs.readFileSync(path.join(art, file)).toString('base64');
const data = {version: 'colosse-aseprite-v'+manifest.version, size: manifest.sheetSize, death: manifest.death, clips, png: dataURL(manifest.sheet), grip: dataURL(manifest.gripSheet)};
const file = path.join(root, 'index.html');
const html = fs.readFileSync(file, 'utf8');
const block = /\/\/ BEGIN GUARDIAN ASSETS[^\n]*\n[\s\S]*?\/\/ END GUARDIAN ASSETS/;
if (!block.test(html)) throw new Error('Missing guardian asset markers');
const updated = html.replace(block, '// BEGIN GUARDIAN ASSETS (generated by scripts/embed-guardian.cjs)\nconst CO_ART=' + JSON.stringify(data) + ';\n// END GUARDIAN ASSETS');
fs.writeFileSync(file, updated);
// The bundled fallback omits only web app links; all executable game code is identical.
fs.writeFileSync(path.join(root, 'ios/Hearthreaver/Game/index.html'), updated.replace(/<meta name="apple-mobile-web-app-title"[^>]*><link rel="apple-touch-icon"[^>]*><link rel="manifest"[^>]*>/, ''));
console.log('Embedded '+manifest.clips.length+' clips and grasp overlay; synchronized the iOS fallback.');
